using CUE4Parse.Compression;
using CUE4Parse.FileProvider;
using CUE4Parse.MappingsProvider;
using CUE4Parse.UE4.Versions;
using Newtonsoft.Json;

var oodle = Path.GetFullPath(OodleHelper.OODLE_DLL_NAME);  // build it with tools/oodle-shim (the old CUE4Parse download source no longer works)
if (!File.Exists(oodle)) Console.WriteLine($"oodle download: {await OodleHelper.DownloadOodleDllAsync(oodle)} -> {File.Exists(oodle)}");
OodleHelper.Initialize(oodle);

var dir = @"C:\Program Files (x86)\Steam\steamapps\common\Rematch\Runtime\Content\Paks";
var p = new DefaultFileProvider(dir, SearchOption.TopDirectoryOnly, new VersionContainer(EGame.GAME_UE5_LATEST));
p.Initialize();
p.Mount();
if (args.Contains("--script")) p.ReadScriptData = true;  // include Blueprint (Kismet) bytecode in the JSON
if (File.Exists("Rematch.usmap")) p.MappingsContainer = new FileUsmapTypeMappingsProvider("Rematch.usmap");  // generated by tools/usmapgen.py
if (args.Contains("--list")) { File.WriteAllLines("files.txt", p.Files.Keys.OrderBy(k => k)); return; }
Directory.CreateDirectory("out");
var targets = args.FirstOrDefault(a => a.EndsWith(".txt")) ?? "targets.txt";
foreach (var path in File.ReadAllLines(targets).Where(l => l.Length > 0))
{
    try
    {
        var objs = p.LoadPackage(path).GetExports();
        File.WriteAllText(Path.Combine("out", Path.GetFileNameWithoutExtension(path) + ".json"), JsonConvert.SerializeObject(objs, Formatting.Indented));
        Console.WriteLine($"OK {path}");
    }
    catch (Exception e) { Console.WriteLine($"FAIL {path}: {e.GetType().Name}: {e.Message.Split('\n')[0]}"); }
}
